#!/usr/bin/env bash
# Create a fresh coop/server.ini for a LAN or Global SA:COOP story-co-op server.
# Usage: ./create-coop-server.sh [GAME_FOLDER] [--lan|--global]
#        [--name "..."] [--port 7788] [--players 2|3|4]
#        [--password "..."] [--turn "..."] [--no-password]
set -euo pipefail

GAME_DIR="."
MODE=""
NAME=""
PORT="7788"
PLAYERS="2"
PASSWORD=""
TURN=""
NO_PASSWORD=0

usage() {
    cat <<'EOF'
Usage: create-coop-server.sh [GAME_FOLDER] [options]

Creates/overwrites GAME_FOLDER/coop/server.ini with a clean server config.
A backup of the old file is saved as server.ini.bak.

Options:
  --lan                 LAN only (internet = 0)
  --global              Global / online (internet = 1)
  --name "TEXT"         server name shown to friends
  --port NUMBER         UDP port (default 7788)
  --players N           max players: 2, 3 or 4 (default 2)
  --password "TEXT"     server password (empty means no password)
  --no-password         explicitly allow an empty password
  --turn "TEXT"         optional TURN relay for difficult NAT
  -h, --help            show this help

With no mode option the script asks questions interactively.
EOF
}

fail() { echo "ERROR: $*" >&2; exit 1; }

while (( $# )); do
    case "$1" in
        --lan)          MODE=lan; shift ;;
        --global)       MODE=global; shift ;;
        --name)         [[ $# -ge 2 ]] || fail "--name needs a value"; NAME="$2"; shift 2 ;;
        --port)         [[ $# -ge 2 ]] || fail "--port needs a value"; PORT="$2"; shift 2 ;;
        --players)      [[ $# -ge 2 ]] || fail "--players needs a value"; PLAYERS="$2"; shift 2 ;;
        --password)     [[ $# -ge 2 ]] || fail "--password needs a value"; PASSWORD="$2"; shift 2 ;;
        --turn)         [[ $# -ge 2 ]] || fail "--turn needs a value"; TURN="$2"; shift 2 ;;
        --no-password)  NO_PASSWORD=1; shift ;;
        -h|--help)      usage; exit 0 ;;
        -*)             fail "unknown option: $1" ;;
        *)
            if [[ "$GAME_DIR" == "." ]]; then GAME_DIR="$1"; shift
            else fail "unexpected argument: $1"; fi ;;
    esac
done

INTERACTIVE=0
if [[ -z "$MODE" ]]; then
    INTERACTIVE=1
    if [[ -t 0 ]]; then
        echo "SA:COOP server config generator"
        read -r -p "Mode [lan/global]: " MODE
    else
        fail "no mode given; use --lan or --global in non-interactive use"
    fi
fi
case "$MODE" in
    lan|LAN) MODE=lan ;;
    global|GLOBAL|online|ONLINE) MODE=global ;;
    *) fail "mode must be 'lan' or 'global'" ;;
esac

if (( INTERACTIVE )); then
    read -r -p "Server name [My Co-op]: " NAME
    read -r -p "UDP port [$PORT]: " PORT
    read -r -p "Max players 2/3/4 [$PLAYERS]: " PLAYERS
    read -r -s -p "Server password (Enter = none): " PASSWORD
    echo
    read -r -p "TURN relay (Enter = none): " TURN
else
    if [[ -z "$NAME" && -t 0 ]]; then
        read -r -p "Server name [My Co-op]: " NAME
    fi
    if [[ -t 0 && -z "${PASSWORD:-}" && "$MODE" == global && "$NO_PASSWORD" -eq 0 ]]; then
        read -r -s -p "Server password (Enter = none, but not recommended for Global): " PASSWORD
        echo
    fi
fi
[[ -z "$NAME" ]] && NAME="My Co-op"
[[ -z "$PORT" ]] && PORT=7788
[[ -z "$PLAYERS" ]] && PLAYERS=2

[[ -z "${NAME//[[:space:]]/}" ]] && fail "server name cannot be empty"
[[ "$PORT" =~ ^[0-9]+$ ]] && (( 10#$PORT >= 1 && 10#$PORT <= 65535 )) \
    || fail "port must be a number from 1 to 65535"
[[ "$PLAYERS" == 2 || "$PLAYERS" == 3 || "$PLAYERS" == 4 ]] \
    || fail "max players must be 2, 3 or 4"

if [[ "$MODE" == global && -z "$PASSWORD" && "$NO_PASSWORD" -eq 0 ]]; then
    echo "WARNING: Global mode with no password lets anyone who finds the server join." >&2
    echo "Pass --password \"...\" or --no-password to continue." >&2
    exit 1
fi

COOP_DIR="$GAME_DIR/coop"
CONFIG="$COOP_DIR/server.ini"
[[ -f "$GAME_DIR/gta_sa.exe" ]] || echo "WARNING: gta_sa.exe not found in $GAME_DIR" >&2
mkdir -p "$COOP_DIR"
[[ -f "$CONFIG" ]] && cp -f "$CONFIG" "$CONFIG.bak"

INTERNET=0
[[ "$MODE" == global ]] && INTERNET=1
TMP="$CONFIG.generate.$$"

# SA:COOP expects CRLF line endings; keep comments readable and keys exact.
line() { printf '%s\r\n' "$1"; }
{
    line "; SA:COOP server settings - generated by create-coop-server.sh"
    line "; LAN = internet 0, GLOBAL = internet 1 (UPnP + invite code in F9)."
    line "[server]"
    line "name = $NAME"
    line "port = $PORT"
    line "; Leave password empty only for private LAN games."
    line "password = $PASSWORD"
    line "; How many players can play together: 2 to 4."
    line "max_players = $PLAYERS"
    line "; Nickname of the fixed host. Empty = first player to join becomes host."
    line "host ="
    line "motd = Welcome! Type /help for commands."
    line "friendly_fire = 0"
    line "partner_teleport = 1"
    line "shared_life = 0"
    line "; 1 = play over the internet, 0 = LAN only."
    line "internet = $INTERNET"
    line "; Optional TURN relay: metered:<app>:<api-key>  or  turn:<host>:<port>:<user>:<password>"
    line "turn = $TURN"
} > "$TMP"

chmod --reference="$CONFIG" "$TMP" 2>/dev/null || true
mv -f "$TMP" "$CONFIG"

echo "Created: $CONFIG"
echo "Mode:    $MODE (internet = $INTERNET)"
echo "Name:    $NAME"
echo "Port:    UDP $PORT"
echo "Players: $PLAYERS"
echo "Password: $([[ -z "$PASSWORD" ]] && echo '(none)' || echo '(set)')"
[[ -n "$TURN" ]] && echo "TURN:    set"
[[ -f "$CONFIG.bak" ]] && echo "Backup:  $CONFIG.bak"
echo
echo "Next: close GTA, run ./start-story-coop.sh, press F9, Host a game -> Start the server."
echo "Friends join with this host's LAN IP (LAN) or the F9 invite code / public IP (Global)."
